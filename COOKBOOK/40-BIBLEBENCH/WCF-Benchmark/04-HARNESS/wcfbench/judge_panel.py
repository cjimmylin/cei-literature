#: item.author -> model family (for the §4.3 generator-family exclusion). Opus and
#: Fable are both Anthropic-family authors; override per item via
#: ``extra['generator_family']`` when an item is generated by a specific SUT family.
_AUTHOR_FAMILY = {"opus": "anthropic", "fable": "anthropic"}

# --- R33.4/R33.6 per-surface acceptance --------------------------------------
# A judge is accepted or discarded PER SURFACE, not per-judge globally: the pilot's
# gpt-4o-mini reads per-keypoint awards well but its disclosure channel is a dead
# constant (R30), and gemini-2.5-flash grades disclosure carefully but its OPEN award
# form is holistic all-or-nothing (R29b). Each surface qualifies on the probes that
# actually test it (see :meth:`JudgePanel._qualify`). The surface constants live in
# :mod:`wcfbench.qualification` (single source of truth); re-exported here for callers.
from .qualification import (
    OPEN_AWARD, DISCLOSURE, COHERENCE, SETTLED_CORE, SURFACES,
    manifest_is_fresh, eligible_surfaces_for,
)


def _generator_family(item: ItemRecord) -> str:
    gf = item.extra.get("generator_family")
    if gf:
        return str(gf)
    return _AUTHOR_FAMILY.get((item.author or "").strip().lower(), (item.author or "").strip().lower())


@dataclass
class OpenVerdict:
    """An OPEN item's panel verdict: the aggregated triaxial (axes NEVER collapsed)
    plus a documented substance headline and every judge's raw axis scores."""

    triaxial: TriaxialScore
    headline: Optional[float]                 # Matter-mean / total_points, clamped [0,1] — a
                                              # reporting proxy for the tensor, NOT a collapse
    per_judge: List[Dict[str, Any]] = field(default_factory=list)
    judges_used: List[Tuple[str, str]] = field(default_factory=list)


@dataclass
class ContestedVerdict:
    """A CONTESTED item's panel verdict: the aggregated :class:`ContestedScore`
    (adherence, no correctness scalar) plus every judge's raw scores."""

    score: ContestedScore
    per_judge: List[Dict[str, Any]] = field(default_factory=list)
    judges_used: List[Tuple[str, str]] = field(default_factory=list)


def _mean(vals: List[Optional[float]]) -> Optional[float]:
    present = [v for v in vals if v is not None]
    return (sum(present) / len(present)) if present else None


# --- R40.2 transport-retry seam ----------------------------------------------
#: One retry with a short backoff on a RETRYABLE transport error. The grok AGG-C8 drop
#: (the settled-core floor divergence, memo R38/R39) was a downstream ``JSONDecodeError``
#: raised inside the OpenRouter client — a malformed HTTP body — which surfaces as an
#: *exception* out of the whole scoring function, so the ``complete_with_retry``
#: finish_reason/empty seam (which inspects returned TEXT) never sees it. R40.2 catches it
#: here, retries once, and — on a post-retry failure — records ``fail_transport_after_retry``
#: in the ``discarded`` record. A transport loss is NEVER a silent drop and NEVER a
#: substantive fail (R35.1's principle, applied to the exception path).
_RETRY_BACKOFF_SECS = 0.75
#: HTTP transport codes that warrant a retry (key-limit / rate / auth-transient / billing).
#: 402 = billing (WALKWORTHY parity), 403 = "Key limit exceeded" (the floor-rerun deepseek
#: 403s), 429 = rate limit. A 5xx server error is NOT in this set — it keeps the legacy
#: single-attempt "call error" survival (not a retryable transport class here).
_RETRYABLE_HTTP_CODES = (402, 403, 429)


def is_retryable_transport_error(exc: BaseException) -> bool:
    """True iff ``exc`` is a retryable transport-class failure (R40.2):
      (i)  a ``json.JSONDecodeError`` / an OpenRouterError whose message reports a
           malformed/unparseable reply body (the grok AGG-C8 signature), or
      (ii) an OpenRouter HTTP 402 / 403 / 429 transport error.
    A generic bug (``ValueError``), a simulated upstream 500, or a plain ``RuntimeError``
    is NOT retryable here — it keeps the existing single-attempt per-judge survival."""
    if isinstance(exc, json.JSONDecodeError):
        return True
    msg = str(exc)
    low = msg.lower()
    # An OpenRouter (or any client) "malformed / unparseable response body" is a
    # transport-class parse loss, same class as the grok JSONDecodeError.
    if "malformed" in low or "unparseable" in low or "json" in low or "decode" in low:
        return True
    # HTTP 402/403/429 surfaced in the exception message (OpenRouterError formats
    # `OpenRouter HTTP <code> (<reason>) ...`).
    for code in _RETRYABLE_HTTP_CODES:
        if f"http {code}" in low or f"HTTP {code}".lower() in low:
            return True
    return False


def _score_judge_with_retry(score_fn: Callable[[], Any]) -> Tuple[Any, Optional[str]]:
    """Run ``score_fn`` (one judge's scoring call, which may fan out several ``.complete``
    calls); on a RETRYABLE transport error retry ONCE after a short backoff. Returns
    ``(result, reason)`` where ``result`` is the score object on success (``reason`` None),
    or ``(None, reason)`` on failure — ``reason`` is ``"fail_transport_after_retry: …"`` for
    a retryable error that survived the retry, or ``"call error …"`` for a non-retryable
    per-judge error (the legacy single-attempt survival). NEVER a silent drop."""
    try:
        return score_fn(), None
    except Exception as e:  # noqa: BLE001 — per-judge survival; classify below
        if not is_retryable_transport_error(e):
            return None, f"call error: {type(e).__name__}"
        first = f"{type(e).__name__}: {str(e)[:80]}"
        time.sleep(_RETRY_BACKOFF_SECS)
        try:
            return score_fn(), None
        except Exception as e2:  # noqa: BLE001
            return None, (f"fail_transport_after_retry: {type(e2).__name__} "
                          f"(first: {first})")


class JudgePanel:
    """A calibrated, cross-family judge panel driving the OPEN + CONTESTED paths."""

    def __init__(self, judges: List[Any], *, k: int = 2, calibrate: bool = True,
                 manifest: Optional[Dict[str, Any]] = None) -> None:
        norm: List[Tuple[str, str, Any, str]] = []
        for j in judges:
            if isinstance(j, dict):
                slug = str(j.get("slug", j["name"]))
                norm.append((str(j["name"]), str(j["family"]), j["client"], slug))
            else:
                slug = str(j[3]) if len(j) > 3 else str(j[0])
                norm.append((str(j[0]), str(j[1]), j[2], slug))
        self.k = k
        self.discarded: List[Tuple[str, str]] = []          # (name, reason) fully-discarded + cell discards
        #: R33.4: name -> the set of SURFACES the judge qualified for. A judge with an
        #: empty set is fully discarded; a partial set is per-surface SUSPENDED (R33.6).
        self.eligible: Dict[str, set] = {}
        active: List[Tuple[str, str, Any]] = []

        if manifest is not None:
            # R35.4: consume a FROZEN qualification manifest — no probes run at construction,
            # so run-to-run eligibility cannot flip. Re-qualification (a new manifest) is
            # required only on a slug change, a template-hash drift, or a binding-memo order.
            self.manifest = manifest
            if not manifest_is_fresh(manifest):
                raise JudgeError(
                    "qualification manifest is STALE — a prompt-template hash has drifted since "
                    "it was frozen; re-qualify the panel (probe_stability + build_manifest) (R35.4)")
            for name, family, client, slug in norm:
                elig = eligible_surfaces_for(manifest, slug)
                if elig is None:
                    self.discarded.append(
                        (name, f"not in qualification manifest (slug {slug}) — re-qualify (R35.4)"))
                    continue
                if not elig:
                    self.discarded.append((name, f"manifest: no surface qualified (slug {slug})"))
                    continue
                self.eligible[name] = set(elig)
                active.append((name, family, client))
                suspended = set(SURFACES) - set(elig)
                if suspended:                              # per-surface suspension surfaced (not a discard)
                    self.discarded.append(
                        (name, f"per-surface SUSPENDED for {sorted(suspended)} — manifest {slug}"))
        elif calibrate:
            for name, family, client, slug in norm:
                elig, why = self._qualify(client)
                if elig:
                    self.eligible[name] = elig
                    active.append((name, family, client))
                    suspended = set(SURFACES) - elig
                    if suspended:                          # per-surface suspension (not a discard)
                        self.discarded.append(
                            (name, f"per-surface SUSPENDED for {sorted(suspended)} — {why}"))
                else:
                    self.discarded.append((name, f"discarded (no surface qualified) — {why}"))
        else:
            for name, family, client, slug in norm:
                self.eligible[name] = set(SURFACES)
                active.append((name, family, client))

        self.active = active
        fams = {f for _, f, _ in active}
        if len(active) < 2 or len(fams) < 2:
            raise JudgeError(
                f"unusable panel after calibration: {len(active)} judge(s) across families "
                f"{sorted(fams)} — spine §4.3 needs ≥2 judges spanning ≥2 families (each "
                f"eligible for ≥1 surface). Discarded: {self.discarded}"
            )

    @staticmethod
    def _qualify(client: Any) -> Tuple[set, str]:
        """Run the extended acceptance battery (R33.4) and return the set of SURFACES the
        judge qualified for + a human note. Mapping (probe → surface it gates):
          - OPEN_AWARD  = G4 ∧ award-consistency ∧ discrimination
          - DISCLOSURE  = disclosure-inversion ∧ negative-disclosure
          - COHERENCE   = G4    (the polish/charity calibration a coherence grade needs)
          - SETTLED_CORE= G4
        This reproduces R33.6's provisional status when a judge still fails: gpt (dead
        disclosure channel) keeps OPEN award / coherence / settled-core but loses
        disclosure; gemini (holistic award form) keeps disclosure / coherence /
        settled-core but loses OPEN award — while re-admitting a judge that now passes."""
        notes: List[str] = []
        g4 = not run_judge_calibration(client).flagged
        if not g4:
            notes.append("G4 miscalibrated")
        ac = run_award_consistency_probe(client).passed
        if not ac:
            notes.append("award-consistency failed")
        disc = run_discrimination_probe(client).passed
        if not disc:
            notes.append("discrimination failed (holistic all-or-nothing)")
        di = run_disclosure_inversion_probe(client).passed
        if not di:
            notes.append("disclosure-inversion failed")
        neg = run_negative_disclosure_probe(client).passed
        if not neg:
            notes.append("negative-disclosure failed (over-credits a settled order)")
        elig = set()
        if g4 and ac and disc:
            elig.add(OPEN_AWARD)
        if di and neg:
            elig.add(DISCLOSURE)
        if g4:
            elig.update({COHERENCE, SETTLED_CORE})
        return elig, ("; ".join(notes) if notes else "all probes passed")

    # -- per-item judge assignment (cross-family, generator excluded) ---------
    def _assign(self, item: ItemRecord) -> List[Tuple[str, str, Any]]:
        gen_family = _generator_family(item)
        meta = [(name, family) for name, family, _ in self.active]
        # k is a TARGET, not a hard floor: excluding the generator family may leave
        # fewer than k judges. Cap k to the eligible count so a valid cross-family
        # pair is still assigned (assign_judges still enforces the ≥2-family minimum).
        eligible = sum(1 for _, f in meta if f != gen_family)
        k_eff = max(2, min(self.k, eligible)) if eligible >= 2 else self.k
        assignment = assign_judges(gen_family, meta, k=k_eff)
        by_name = {name: (name, family, client) for name, family, client in self.active}
        return [by_name[name] for name, _ in assignment.judges if name in by_name]

    # -- OPEN: triaxial across the assigned judges ----------------------------
    def score_open(self, item: ItemRecord, response: str) -> OpenVerdict:
        judges = self._assign(item)
        per_judge: List[Dict[str, Any]] = []
        used: List[Tuple[str, str]] = []
        for name, family, client in judges:
            # R40.2: one retry with backoff on a retryable transport error (JSONDecodeError /
            # HTTP 402/403/429); a post-retry loss is recorded fail_transport_after_retry,
            # never a silent drop. A non-transport bug keeps the legacy single-attempt survival.
            t, err = _score_judge_with_retry(
                lambda c=client: score_triaxial(stem=item.stem, rubric=item.rubric,
                                                response=response, judge=c, item_id=item.id))
            if err is not None:
                self.discarded.append((name, f"{err} on {item.id}"))
                continue
            # R33.3: an award call still truncated/short after one retry is discarded for
            # THIS cell (surfaced), never absorbed as a real low grade.
            if getattr(t, "truncated_discarded", False):
                self.discarded.append(
                    (name, f"award call truncated/short on {item.id} after retry — cell-discarded (R33.3)"))
                continue
            per_judge.append({"name": name, "family": family,
                              "matter": t.matter, "manner": t.manner, "end": t.end,
                              "graded": dict(t.graded),
                              # R24: keypoint-level awards + off-scale flags (the
                              # keypoint-level disagreement payload) + OFFMAP notes.
                              "awards": dict(t.awards), "award_axis": dict(t.award_axis),
                              "scale_defect": dict(t.scale_defect), "offmap": list(t.offmap),
                              # R33.1/R33.3: compliance defects + truncation finish_reason.
                              "compliance_defects": dict(t.compliance_defects),
                              "finish_reason": t.finish_reason, "retried": t.retried,
                              # R33.4: the surfaces this judge qualified for (aggregation
                              # excludes an OPEN-award-suspended judge; raw survives here).
                              "eligible_surfaces": sorted(self.eligible.get(name, set())),
                              # R27: the judge's verbatim verdict text(s).
                              "verdict_texts": list(t.raw_verdicts)})
            used.append((name, family))
        agg = self._aggregate_triaxial(per_judge)
        # axes are graded on a 0..1 scale (§4.2 judge contract), so the Matter axis IS
        # the [0,1] substance headline — a documented reporting proxy for the tensor,
        # NOT a collapse (Manner/End stay separate on `triaxial`). Clamp defensively.
        headline = None if agg.matter is None else max(0.0, min(1.0, agg.matter))
        return OpenVerdict(triaxial=agg, headline=headline, per_judge=per_judge, judges_used=used)

    @staticmethod
    def _aggregate_triaxial(per_judge: List[Dict[str, Any]]) -> TriaxialScore:
        agg = TriaxialScore()
        # R33.4: the three OPEN axes aggregate ONLY over judges qualified for the
        # OPEN-award surface — a judge whose award form is holistic all-or-nothing (R29b)
        # is suspended here; its raw award still lives on per_judge as the disagreement
        # record. (When per_judge predates R33.4 it carries no surface list → included.)
        open_ok = [j for j in per_judge
                   if "eligible_surfaces" not in j or OPEN_AWARD in j.get("eligible_surfaces", [])]
        susp = len(per_judge) - len(open_ok)
        for axis in ("matter", "manner", "end"):
            # R24 bullet 5: exclude a per-judge axis value flagged off-scale
            # (scale_defect) from the aggregate — never clamp it in. The raw value
            # still lives on per_judge as the disagreement evidence.
            vals = [j[axis] for j in open_ok if not j.get("scale_defect", {}).get(axis)]
            excluded = sum(1 for j in open_ok if j.get("scale_defect", {}).get(axis))
            m = _mean(vals)
            setattr(agg, axis, m)
            agg.graded[axis] = m is not None
            note = f"mean of {sum(1 for v in vals if v is not None)} OPEN-award judge(s)"
            if excluded:
                note += f" ({excluded} off-scale excluded)"
            if susp:
                note += f" ({susp} OPEN-award-suspended excluded)"
            agg.detail[axis] = note
        return agg

    # -- CONTESTED: position/coherence across the assigned judges -------------
    def score_contested(self, item: ItemRecord, response: str, ranking: Any = None) -> ContestedVerdict:
        judges = self._assign(item)
        raw: List[Dict[str, Any]] = []
        used: List[Tuple[str, str]] = []
        scored: List[Tuple[ContestedScore, set]] = []   # (score, eligible-surfaces)
        for name, family, client in judges:
            # R40.2: one retry with backoff on a retryable transport error (the grok AGG-C8
            # JSONDecodeError signature / HTTP 402/403/429); a post-retry loss is recorded
            # fail_transport_after_retry, never a silent drop.
            s, err = _score_judge_with_retry(
                lambda c=client: score_contested_position(item=item, response=response,
                                                          judge=c, ranking=ranking, item_id=item.id))
            if err is not None:
                self.discarded.append((name, f"{err} on {item.id}"))
                continue
            # R33.3: a disclosure award call still truncated/short after one retry is
            # discarded for THIS cell (surfaced), never absorbed as a real low score.
            if getattr(s, "truncated_discarded", False):
                self.discarded.append(
                    (name, f"disclosure call truncated/short on {item.id} after retry — cell-discarded (R33.3)"))
                continue
            elig = self.eligible.get(name, set(SURFACES))
            scored.append((s, elig))
            raw.append({"name": name, "family": family, "disclosure": s.disclosure,
                        "position_label": s.position_label, "position_defensible": s.position_defensible,
                        "coherence": s.coherence, "settled_core_fraction": s.settled_core_fraction,
                        # R24 off-scale flags + R28 disclosure award pattern + R27 texts.
                        "scale_defect": dict(s.scale_defect),
                        "disclosure_awards": dict(s.disclosure_awards),
                        # R33.1/R33.3: compliance defects + disclosure truncation reason.
                        "compliance_defects": dict(s.compliance_defects),
                        "finish_reason": s.finish_reason, "retried": s.retried,
                        # R33.4: surfaces this judge qualified for (per-surface aggregation).
                        "eligible_surfaces": sorted(elig),
                        "verdict_texts": list(s.raw_verdicts)})
            used.append((name, family))
        return ContestedVerdict(score=self._aggregate_contested(scored), per_judge=raw, judges_used=used)

    @staticmethod
    def _aggregate_contested(scored: List[Tuple[ContestedScore, set]]) -> ContestedScore:
        """Aggregate the contested axes PER SURFACE (R33.4): disclosure over
        DISCLOSURE-eligible judges only (gpt's dead channel is suspended, R30), coherence
        over COHERENCE-eligible, settled-core over SETTLED_CORE-eligible. Position
        attribution is not a gated surface → aggregated over every judge. The raw per-judge
        values (including a suspended judge's) survive on ``per_judge`` as the disagreement
        record."""
        agg = ContestedScore()
        if not scored:
            return agg
        scores = [s for s, _ in scored]
        disc_ok = [s for s, e in scored if DISCLOSURE in e]
        coh_ok = [s for s, e in scored if COHERENCE in e]
        core_ok = [s for s, e in scored if SETTLED_CORE in e]

        agg.disclosure = _mean([s.disclosure for s in disc_ok])
        # R24 bullet 5: exclude a per-judge coherence flagged off-scale from the
        # aggregate (raw survives on per_judge). Disclosure is the award form → in-range.
        agg.coherence = _mean([s.coherence for s in coh_ok if not s.scale_defect.get("coherence")])
        agg.graded["disclosure"] = agg.disclosure is not None
        agg.graded["coherence"] = agg.coherence is not None
        # position defensibility = majority vote across judges that ruled (not gated)
        votes = [s.position_defensible for s in scores if s.position_defensible is not None]
        if votes:
            agg.position_defensible = sum(1 for v in votes if v) > len(votes) / 2
        # keep the distinct position labels for the disagreement record
        labels = [s.position_label for s in scores if s.position_label]
        agg.position_label = labels[0] if labels else None
        agg.positions_offered = scores[0].positions_offered
        # settled-core = majority per keypoint over SETTLED_CORE-eligible judges.
        # R40.3 / R39(e)(4): an EVEN eligible-judge split is UNGRADED (None) + an
        # escalation flag — NEVER a silent False (the old tie→False rule at judge_panel.py
        # produced the mechanical part of the AGG-C8 0.0: grok's JSONDecodeError drop left
        # an even 2-judge panel, and a 1-1 tie resolved to False = a spurious floor break).
        # An odd-panel majority is unchanged (a genuine majority-wrong keypoint stays a REAL
        # False — the floor is credit-when-earned, R39(e)(3)).
        keys = set()
        for s in core_ok:
            keys.update(s.settled_core)
        escalated: List[str] = []
        for kp in keys:
            kp_votes = [s.settled_core[kp] for s in core_ok if kp in s.settled_core]
            trues = sum(1 for v in kp_votes if v)
            if len(kp_votes) % 2 == 0 and trues == len(kp_votes) / 2:
                agg.settled_core[kp] = None          # UNGRADED tie — escalate, not a False
                escalated.append(kp)
            else:
                agg.settled_core[kp] = trues > len(kp_votes) / 2
        agg.detail["judges"] = (f"per-surface aggregate — disclosure×{len(disc_ok)} "
                                f"coherence×{len(coh_ok)} settled×{len(core_ok)} of {len(scores)}")
        agg.detail["settled_core_escalation"] = (
            "ESCALATE: even eligible-judge split (UNGRADED, R40.3) on settled-core "
            f"keypoint(s): {escalated}" if escalated else "")
        return agg

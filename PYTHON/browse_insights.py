#!/usr/bin/env python3
"""
Browse and search insight logs generated by InsightLogger.

Usage:
    python browse_insights.py --severity critical --days 7
    python browse_insights.py --paper "2024-Smith-AI Safety.md"
    python browse_insights.py --category reclassification --script classify_ethics
    python browse_insights.py --merge --date 20260314 --script classify_ethics
    python browse_insights.py --summary --days 30
"""

import argparse
import json
import os
import sys
from datetime import datetime, timedelta
from pathlib import Path

# Path setup
_SCRIPT_DIR = Path(__file__).parent
sys.path.insert(0, str(_SCRIPT_DIR))
sys.path.insert(0, str(_SCRIPT_DIR.parent / ".agent" / "lib"))

from config import LOGS_DIR


def find_insight_files(days: int = None, script: str = None,
                       date: str = None) -> list:
    """Find insight JSON files matching criteria."""
    if not LOGS_DIR.exists():
        return []

    files = sorted(LOGS_DIR.glob("*-insights-*.json"))

    if date:
        files = [f for f in files if f.name.startswith(date)]

    if script:
        files = [f for f in files if f"-insights-{script}-" in f.name]

    if days is not None:
        cutoff = datetime.now() - timedelta(days=days)
        cutoff_str = cutoff.strftime("%Y%m%d")
        files = [f for f in files if f.name[:8] >= cutoff_str]

    return files


def load_insights(files: list) -> list:
    """Load and merge insights from multiple JSON files."""
    all_insights = []
    for fp in files:
        try:
            data = json.loads(fp.read_text(encoding="utf-8"))
            meta = data.get("meta", {})
            for ins in data.get("insights", []):
                ins["_source_file"] = fp.name
                ins["_script"] = meta.get("script", "unknown")
                all_insights.append(ins)
        except (json.JSONDecodeError, IOError) as e:
            print(f"Warning: Could not read {fp.name}: {e}", file=sys.stderr)
    return all_insights


def filter_insights(insights: list, severity: str = None,
                    category: str = None, paper: str = None) -> list:
    """Filter insights by severity, category, or paper name."""
    result = insights

    if severity:
        result = [i for i in result if i.get("severity") == severity]

    if category:
        result = [i for i in result if i.get("category") == category]

    if paper:
        paper_lower = paper.lower()
        result = [i for i in result
                  if paper_lower in i.get("paper", "").lower()]

    return result


def print_table(insights: list):
    """Print insights as a formatted table."""
    if not insights:
        print("No insights found.")
        return

    # Header
    print(f"{'#':>4}  {'Severity':<10} {'Category':<18} {'Paper':<40} Message")
    print("-" * 120)

    for i, ins in enumerate(insights, 1):
        sev = ins.get("severity", "?")
        cat = ins.get("category", "?")
        paper = ins.get("paper", "")
        if len(paper) > 38:
            paper = paper[:35] + "..."
        msg = ins.get("message", "")
        if len(msg) > 55:
            msg = msg[:52] + "..."
        print(f"{i:>4}  {sev:<10} {cat:<18} {paper:<40} {msg}")

    print(f"\nTotal: {len(insights)} insights")


def print_summary(files: list):
    """Print a summary across all matching log files."""
    if not files:
        print("No insight logs found.")
        return

    total_insights = 0
    total_by_severity = {}
    total_by_category = {}
    scripts_seen = set()

    for fp in files:
        try:
            data = json.loads(fp.read_text(encoding="utf-8"))
            meta = data.get("meta", {})
            total_insights += meta.get("total_insights", 0)
            scripts_seen.add(meta.get("script", "unknown"))

            for sev, count in meta.get("by_severity", {}).items():
                total_by_severity[sev] = total_by_severity.get(sev, 0) + count
            for cat, count in meta.get("by_category", {}).items():
                total_by_category[cat] = total_by_category.get(cat, 0) + count
        except (json.JSONDecodeError, IOError):
            pass

    print(f"{'='*60}")
    print("INSIGHT LOG SUMMARY")
    print(f"{'='*60}")
    print(f"Log files:   {len(files)}")
    print(f"Scripts:     {', '.join(sorted(scripts_seen))}")
    print(f"Total:       {total_insights} insights")
    print()

    print("By Severity:")
    for sev in ["critical", "notable", "info"]:
        count = total_by_severity.get(sev, 0)
        if count:
            print(f"  {sev:<12} {count:>6}")

    print("\nBy Category:")
    for cat, count in sorted(total_by_category.items(), key=lambda x: -x[1]):
        print(f"  {cat:<20} {count:>6}")

    print(f"\n{'='*60}")


def merge_logs(files: list, date: str, script: str):
    """Merge multiple PID-scoped log files into one consolidated file.

    Creates a NEW file (never overwrites originals — vault immutability rule).
    """
    if not files:
        print("No files to merge.")
        return

    all_insights = []
    all_metas = []

    for fp in files:
        try:
            data = json.loads(fp.read_text(encoding="utf-8"))
            all_metas.append(data.get("meta", {}))
            all_insights.extend(data.get("insights", []))
        except (json.JSONDecodeError, IOError) as e:
            print(f"Warning: Could not read {fp.name}: {e}", file=sys.stderr)

    if not all_insights:
        print("No insights found to merge.")
        return

    # Re-number insights sequentially
    for i, ins in enumerate(all_insights, 1):
        ins["id"] = i

    # Build merged meta
    by_category = {}
    by_severity = {}
    for ins in all_insights:
        cat = ins.get("category", "unknown")
        sev = ins.get("severity", "info")
        by_category[cat] = by_category.get(cat, 0) + 1
        by_severity[sev] = by_severity.get(sev, 0) + 1

    earliest = min((m.get("started", "") for m in all_metas), default="")
    latest = max((m.get("finished", "") for m in all_metas), default="")

    merged_meta = {
        "script": script or "merged",
        "merged_from": [fp.name for fp in files],
        "pid": "merged",
        "started": earliest,
        "finished": latest,
        "total_insights": len(all_insights),
        "by_category": by_category,
        "by_severity": by_severity,
    }

    # Write merged file with NEW name (never overwrite)
    out_stem = f"{date}-insights-{script or 'all'}-merged"
    out_path = LOGS_DIR / f"{out_stem}.json"

    # Ensure unique name if file already exists
    counter = 2
    while out_path.exists():
        out_path = LOGS_DIR / f"{out_stem}-{counter}.json"
        counter += 1

    merged_data = {"meta": merged_meta, "insights": all_insights}
    tmp_path = LOGS_DIR / f".tmp.{os.getpid()}.merge.json"
    tmp_path.write_text(
        json.dumps(merged_data, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )
    os.replace(str(tmp_path), str(out_path))

    print(f"Merged {len(files)} files -> {out_path.name}")
    print(f"Total insights: {len(all_insights)}")


def main():
    parser = argparse.ArgumentParser(
        description="Browse and search InsightLogger logs")

    parser.add_argument("--severity", choices=["critical", "notable", "info"],
                        help="Filter by severity level")
    parser.add_argument("--category",
                        help="Filter by category (reclassification, anomaly, etc.)")
    parser.add_argument("--paper", help="Filter by paper name (substring match)")
    parser.add_argument("--script", help="Filter by script name")
    parser.add_argument("--days", type=int, help="Only show logs from last N days")
    parser.add_argument("--date", help="Filter by date prefix (YYYYMMDD)")
    parser.add_argument("--summary", action="store_true",
                        help="Show summary across all matching logs")
    parser.add_argument("--merge", action="store_true",
                        help="Merge PID-scoped logs into one consolidated file")
    parser.add_argument("--json", action="store_true",
                        help="Output results as JSON")

    args = parser.parse_args()

    # Find matching files
    files = find_insight_files(days=args.days, script=args.script,
                               date=args.date)

    if args.merge:
        if not args.date:
            print("Error: --merge requires --date (YYYYMMDD)", file=sys.stderr)
            sys.exit(1)
        merge_logs(files, args.date, args.script)
        return

    if args.summary:
        print_summary(files)
        return

    # Load and filter insights
    insights = load_insights(files)
    insights = filter_insights(insights, severity=args.severity,
                               category=args.category, paper=args.paper)

    if args.json:
        print(json.dumps(insights, indent=2, ensure_ascii=False, default=str))
    else:
        print_table(insights)


if __name__ == "__main__":
    main()

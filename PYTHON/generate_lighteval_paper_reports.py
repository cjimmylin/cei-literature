#!/usr/bin/env python3
"""
generate_lighteval_paper_reports.py — Per-paper detail reports.

Agent 10: Loads merged scores + original data, generates detailed
per-paper reports for papers scoring >= 5.0, with appendix for the rest.

Output: STATISTICS/20260312-lighteval-paper-reports.md
"""

import functools
import json
import sys
from pathlib import Path

print = functools.partial(print, flush=True)

# Path setup
_script_dir = Path(__file__).resolve().parent
if str(_script_dir) not in sys.path:
    sys.path.insert(0, str(_script_dir))

from lighteval_scoring import format_paper_detail, format_paper_summary_line

# ── Paths ────────────────────────────────────────────────────────────────────
BASE = Path(__file__).resolve().parent.parent  # CEI-Lit-WS/
LOGS = BASE / "logs"
STATS = BASE / "STATISTICS"

MERGED_JSON = LOGS / "20260312-lighteval-scores-merged.json"
INPUT_JSON = LOGS / "20260312-lm-eval-implementability-data.json"
REPORT_PATH = STATS / "20260312-lighteval-paper-reports.md"

TODAY = "2026-03-12"
DETAIL_THRESHOLD = 5.0


def main():
    print("Loading merged scores...")
    with open(MERGED_JSON) as f:
        merged = json.load(f)
    results = merged["results"]
    print(f"  {len(results)} scored papers")

    print("Loading original paper data...")
    with open(INPUT_JSON) as f:
        original = json.load(f)
    # Build lookup by filename
    paper_lookup = {p["filename"]: p for p in original["papers"]}

    # Split into detail vs appendix
    detail_papers = [r for r in results if r["total_score"] >= DETAIL_THRESHOLD]
    appendix_papers = [r for r in results if r["total_score"] < DETAIL_THRESHOLD]

    print(f"  Detail reports: {len(detail_papers)} (score >= {DETAIL_THRESHOLD})")
    print(f"  Appendix: {len(appendix_papers)} (score < {DETAIL_THRESHOLD})")

    # ── Build report ─────────────────────────────────────────────────────
    lines = [
        f"# lighteval Per-Paper Implementability Reports",
        f"",
        f"**Generated:** {TODAY}  ",
        f"**Total papers:** {len(results)}  ",
        f"**Detailed reports:** {len(detail_papers)} (score ≥ {DETAIL_THRESHOLD})  ",
        f"**Appendix:** {len(appendix_papers)} (score < {DETAIL_THRESHOLD})",
        f"",
        f"## Table of Contents",
        f"",
        f"- [Detailed Reports](#detailed-reports) ({len(detail_papers)} papers)",
        f"- [Appendix: Below Threshold](#appendix-below-threshold) ({len(appendix_papers)} papers)",
        f"",
        f"---",
        f"",
        f"## Detailed Reports",
        f"",
    ]

    for i, result in enumerate(detail_papers, 1):
        paper = paper_lookup.get(result["filename"], {})
        detail = format_paper_detail(result, paper)
        lines.append(detail)
        if i % 50 == 0:
            print(f"  Formatted {i}/{len(detail_papers)} detail reports")

    # Appendix
    lines.append("## Appendix: Below Threshold")
    lines.append("")
    lines.append("| Paper | Score | Tier | Task Type | Notes |")
    lines.append("|-------|-------|------|-----------|-------|")
    for result in appendix_papers:
        lines.append(format_paper_summary_line(result))
    lines.append("")
    lines.append("---")
    lines.append(f"*Generated by `generate_lighteval_paper_reports.py` on {TODAY}*")
    lines.append("")

    # Write
    report = "\n".join(lines)
    with open(REPORT_PATH, "w") as f:
        f.write(report)
    print(f"Wrote {REPORT_PATH.name} ({len(report):,} bytes)")


if __name__ == "__main__":
    main()
